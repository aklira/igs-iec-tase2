"""S3: the load run. The load driver (igstase2-load, bench/client) runs several associations against the device of the
load run (igstase2-server with 10 000 points, service device-load, generated by bench/device/gen_load_config.py). The
test checks the driver's own counters: no error, no report that belongs to another association, and the number of reads
the workload implies. The latencies are printed; docs/load-test.md records them.
"""

from __future__ import annotations

import math
import re
import subprocess
import sys
from pathlib import Path

import pytest

from igs_bench.compose import Bench

DEVICE_DIR = Path(__file__).resolve().parent.parent / "device"
DEVICE = "172.31.110.12:102"
CLIENT_SERVICE = "client-tase2"
LOAD = "/usr/local/bin/igstase2-load"
POINTS = 10_000
CLIENTS = 8
CHUNK = 100
ROUNDS = 1
WRITES = 10


@pytest.fixture(scope="module")
def bench():
    """One bench for the load run: the device of 10 000 points and the client that runs the driver."""
    subprocess.run([sys.executable, str(DEVICE_DIR / "gen_load_config.py"), str(POINTS)], check=True)
    instance = Bench("s3-load.pcap")
    instance.down()
    instance.up("device-load", CLIENT_SERVICE)
    try:
        yield instance
    finally:
        instance.down()


def counters(text: str) -> dict[str, int]:
    """The `errors=N stray_reports=M` line of the driver."""
    match = re.search(r"errors=(\d+) stray_reports=(\d+)", text)
    assert match, text
    return {"errors": int(match.group(1)), "stray_reports": int(match.group(2))}


def read_count(text: str) -> int:
    match = re.search(r"^read\s+n=(\d+)", text, re.MULTILINE)
    assert match, text
    return int(match.group(1))


def test_many_associations_read_and_write_ten_thousand_points(bench):
    result = bench.exec(
        CLIENT_SERVICE,
        LOAD,
        "--server",
        DEVICE,
        "--points",
        str(POINTS),
        "--clients",
        str(CLIENTS),
        "--rounds",
        str(ROUNDS),
        "--chunk",
        str(CHUNK),
        "--writes",
        str(WRITES),
        timeout=900,
        check=False,
    )
    print(result.stdout)
    assert result.returncode == 0, result.stdout + result.stderr
    assert counters(result.stdout) == {"errors": 0, "stray_reports": 0}, result.stdout
    # Each client reads every chunk of every round: the driver's read count follows from the workload.
    expected_reads = CLIENTS * ROUNDS * math.ceil(POINTS / CHUNK)
    assert read_count(result.stdout) == expected_reads, result.stdout


def test_the_driver_refuses_a_server_that_is_not_there(bench):
    result = bench.exec(
        CLIENT_SERVICE,
        LOAD,
        "--server",
        "172.31.110.250:102",
        "--points",
        "2",
        "--clients",
        "1",
        "--timeout-s",
        "3",
        timeout=60,
        check=False,
    )
    assert result.returncode != 0, result.stdout
