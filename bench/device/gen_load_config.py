"""Writes bench/device/load-10k.toml: the configuration of the device under test for the load run (task S3).

The file holds the same server as `igstase2-load --local` (crates/igstase2-load/src/local.rs): N writable integer points
P00000 ... in the domain ICC1, the Bilateral Table of the load clients (AP-title 1.3.9999.1, table BT-2026-001), the data set
DS1 on P00000, and the transfer set TS1. The file is large and is generated, not versioned (device/.gitignore).

Usage: python3 gen_load_config.py [POINTS]   (default 10000)
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def point(index: int) -> str:
    return f'[[point]]\ndomain = "ICC1"\nname = "P{index:05d}"\ntype = "integer"\nbits = 32\nvalue = 0\nwritable = true\n'


def access(index: int) -> str:
    return (
        '[[table.access]]\nkind = "data-value"\n'
        f'name = "P{index:05d}"\n'
        'permissions = ["visibility", "get-data-value", "set-data-value", "get-data-value-type"]\n'
    )


def generate(points: int) -> str:
    parts = [
        "# GENERATED by bench/device/gen_load_config.py: the device under test of the load run (task S3). Do not edit.\n",
        '[identity]\nvendor = "igs"\nmodel = "igstase2 load"\nrevision = "0.1"\n\n',
        "[server]\npoll_ms = 50\ndata_set_capacity = 16\n\n",
        '[[domain]]\nname = "ICC1"\n\n',
    ]
    parts += [point(i) for i in range(points)]
    parts.append('\n[[data-set]]\ndomain = "ICC1"\nname = "DS1"\nmembers = ["P00000"]\n\n')
    parts.append('[[transfer-set]]\ndomain = "ICC1"\nname = "TS1"\n\n')
    parts.append(
        '[[table]]\ndesignation = "1.3.9999.1"\ntable_id = "BT-2026-001"\ndomain = "ICC1"\n'
        'application_references = ["1.3.9999.1"]\ndata_set_creation = true\n'
    )
    parts += [access(i) for i in range(points)]
    parts.append(
        '[[table.access]]\nkind = "data-set"\nname = "DS1"\n'
        'permissions = ["visibility", "delete-data-set", "get-data-set-element-values", "set-data-set-element-values"]\n'
    )
    parts.append(
        '[[table.access]]\nkind = "transfer-set"\nname = "TS1"\n'
        'permissions = ["visibility", "start-transfer", "stop-transfer"]\n'
    )
    return "".join(parts)


if __name__ == "__main__":
    count = int(sys.argv[1]) if len(sys.argv) > 1 else 10000
    target = HERE / "load-10k.toml"
    target.write_text(generate(count), encoding="utf-8")
    print(f"wrote {target} ({count} points)")
